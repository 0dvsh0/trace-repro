"""Compilation of the causal subgraph into a runnable pytest file.

The generated artefact has to survive being committed to a repository that does
not have trace-repro installed, so these tests check that it is valid, honest
Python that carries only facts that came out of the graph.
"""

from __future__ import annotations

import ast
import subprocess
import sys

import pytest

from trace_repro.analysis.triage import TriageEngine
from trace_repro.codegen.assets import INSTALL_MAP, harness_files, read_template
from trace_repro.codegen.repro import TargetProfile, compile_test, install_harness

from .conftest import SCENARIOS
from .synthetic import build_incident


@pytest.fixture()
def incident(any_store):
    return TriageEngine(any_store).triage(build_incident(any_store).crash_span_id)


@pytest.fixture()
def compiled(incident, tmp_path):
    profile = TargetProfile.for_repo(tmp_path, incident)
    return compile_test(incident, profile)


def test_generated_test_is_valid_python(compiled):
    ast.parse(compiled.source)
    compile(compiled.source, str(compiled.path), "exec")


def test_generated_test_has_no_absolute_paths(compiled):
    """A build machine's paths must not leak into a committed artefact."""
    assert ":\\" not in compiled.source
    assert "D:/" not in compiled.source
    assert compiled.source.startswith("# Auto-generated by trace-repro")


def test_generated_test_names_every_participant(compiled, incident):
    for step in incident.replay_steps:
        assert repr(step.endpoint) in compiled.source
        assert repr(step.kind) in compiled.source


def test_generated_offsets_come_from_the_graph(compiled, incident):
    for step in incident.replay_steps:
        assert f"offset_ms={step.offset_ms!r}" in compiled.source


def test_generated_test_has_one_step_per_trace(compiled, incident):
    assert f"parties={len(incident.replay_steps)}" in compiled.source
    # Only the CAUSAL_STEPS block counts; the idempotency test builds its own.
    steps_block = compiled.source.split("CAUSAL_STEPS = [")[1].split("\n]")[0]
    assert steps_block.count("Step(") == len(incident.replay_steps)
    assert compiled.participants == len(incident.replay_steps)


def test_generated_test_documents_the_cause(compiled, incident):
    assert incident.crash_function in compiled.source
    assert incident.upstream_mutator in compiled.source
    assert "hazard=WAW" in compiled.source
    for interference in incident.interferences:
        assert interference.other_trace_id in compiled.source


def test_generated_test_asserts_the_corrupt_state(demo_repo):
    """The repository's own contract supplies the domain assertions.

    The graph can prove which write lost the race; only the target repository
    knows what a correct run must look like. Both have to reach the artefact.
    """
    from trace_repro.analysis.triage import TriageEngine
    from trace_repro.codegen.repro import TargetProfile, compile_test

    profile = TargetProfile.for_repo(demo_repo)
    incident = _incident_for_repo(demo_repo, TriageEngine)
    compiled = compile_test(incident, profile, out_dir=demo_repo / "tests" / "repro")

    for statement in profile.assertions:
        assert statement in compiled.source
    assert "CORRUPT_VALUE" in compiled.source
    assert "lost update still wins" in compiled.source or "charged twice" in compiled.source \
        or "written off" in compiled.source


def _incident_for_repo(repo, engine_cls):
    """Triage the incident the scenario repository actually reproduces."""
    from trace_repro.graph.memory import MemoryStore
    from trace_repro.pipeline.workload import reproduce

    store = MemoryStore()
    outcome = reproduce(store, repo_root=str(repo))
    assert outcome.crashed, f"{repo.name} stopped reproducing its incident"
    return engine_cls(store).triage(outcome.crash_span_id, incident_id="incident_demo")


def test_generated_test_imports_the_harness(compiled):
    assert "from tests.repro.harness import" in compiled.source
    assert "from tests.repro.adapters import dispatch" in compiled.source


def test_generated_test_is_lint_clean(compiled, tmp_path):
    """It will be committed to someone else's repo and linted there.

    Only pyflakes-grade checks are asserted: no undefined names, no unused
    imports, no syntax errors. Import *ordering* is deliberately excluded --
    that is each project's own isort configuration to decide.
    """
    import subprocess
    import sys

    compiled.path.parent.mkdir(parents=True, exist_ok=True)
    compiled.path.write_text(compiled.source, encoding="utf-8")
    proc = subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--isolated", "--select", "E9,F",
         str(compiled.path)],
        capture_output=True, text=True, timeout=120,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_generated_test_is_independent_of_trace_repro(compiled):
    """The target repo must not need trace-repro installed to run the test."""
    assert "import trace_repro" not in compiled.source
    assert "from trace_repro" not in compiled.source


def test_corrupt_value_is_derived_not_guessed(incident, tmp_path):
    profile = TargetProfile.for_repo(tmp_path, incident)
    # The worker wrote CANCELLED; that is the value that must never persist.
    assert profile.corrupt_value == "CANCELLED"
    # The webhook's transition is the state a correct run must reach.
    assert profile.expected_value == "AUTHORIZED"


def test_harness_installs_into_the_target_repo(tmp_path):
    profile = TargetProfile.for_repo(tmp_path)
    installed = install_harness(profile)
    assert len(installed) == len(INSTALL_MAP)
    for rel in INSTALL_MAP:
        assert (tmp_path / rel).exists(), rel
    assert (tmp_path / "tests" / "repro" / "__init__.py").exists()

    for rel, content in harness_files().items():
        assert (tmp_path / rel).read_text(encoding="utf-8") == content


def test_install_does_not_clobber_an_edited_harness(tmp_path):
    profile = TargetProfile.for_repo(tmp_path)
    install_harness(profile)
    harness = tmp_path / "tests" / "repro" / "harness.py"
    harness.write_text("# locally customised\n", encoding="utf-8")

    install_harness(profile)
    assert harness.read_text(encoding="utf-8") == "# locally customised\n"

    install_harness(profile, force=True)
    assert "Barrier" in harness.read_text(encoding="utf-8")


def test_demo_harness_matches_the_packaged_template(demo_repo):
    """No scenario repository may drift from what would be installed.

    The harness is deliberately service-free now, so all three repositories
    ship byte-identical copies of the packaged template. If one ever edits it,
    that edit has to become the template.
    """
    for rel, name in INSTALL_MAP.items():
        shipped = (demo_repo / rel).read_text(encoding="utf-8")
        assert shipped == read_template(name), (
            f"{demo_repo.name}/{rel} has drifted from the packaged template"
        )


def test_demo_harness_is_valid_python(demo_repo):
    for rel in INSTALL_MAP:
        source = (demo_repo / rel).read_text(encoding="utf-8")
        compile(source, rel, "exec")


def test_packaged_templates_name_no_service(demo_repo):
    """The harness and adapters must not import a service package.

    They are installed into a repository trace-repro has never seen; the only
    thing they may assume is that the repository itself is importable.
    """
    for rel in INSTALL_MAP:
        source = (demo_repo / rel).read_text(encoding="utf-8")
        for scenario in SCENARIOS:
            assert f"{scenario}_service" not in source, (
                f"{rel} hardcodes the {scenario} service; the dispatch belongs "
                "in the repository's own contract"
            )
        assert "import trace_repro" not in source


def test_generated_test_can_be_collected_by_pytest(compiled, incident, tmp_path):
    """The strongest check: pytest must be able to collect the artefact."""
    install_harness(TargetProfile.for_repo(tmp_path))
    compiled.path.parent.mkdir(parents=True, exist_ok=True)
    compiled.path.write_text(compiled.source, encoding="utf-8")

    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider",
         str(compiled.path.relative_to(tmp_path))],
        cwd=str(tmp_path),
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert f"test_{incident.incident_id}_cross_trace_race" in proc.stdout
    assert f"test_{incident.incident_id}_duplicate_delivery_is_idempotent" in proc.stdout


def test_a_repository_without_a_contract_still_gets_a_valid_test(compiled):
    """Nothing is known about the domain, so nothing is asserted about it.

    The artefact still has to parse, collect and run: a repository that has not
    adopted the contract yet gets the crash assertion and the graph facts, and
    a placeholder that says so out loud.
    """
    assert "incident.json" in compiled.source
    ast.parse(compiled.source)

@pytest.mark.parametrize("scenario", SCENARIOS)
def test_every_scenario_repo_is_runnable(scenario):
    """Each demo repository is a real target: it publishes a contract trace-repro can drive."""
    import ast

    from trace_repro.contract import load_contract

    repo = DEMO / scenario
    spec = load_contract(repo)
    assert spec.package == f"{scenario}_service"
    assert len(spec.participants) >= 3
    assert (repo / spec.package / "db.py").exists()

    for participant in spec.participants:
        route = participant.route or spec.route_for(participant.kind)
        module_name, _, attribute = route.partition(":")
        # ``pkg.module:callable`` -- the callable is defined in pkg/module.py.
        source_file = repo / Path(*module_name.split(".")).with_suffix(".py")
        assert source_file.exists(), f"{route} does not exist in demo/{scenario}"
        defined = {
            node.name
            for node in ast.walk(ast.parse(source_file.read_text(encoding="utf-8")))
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        }
        assert attribute in defined, f"{route} is declared but never defined"

def test_repair_command_dry_run_by_default(capsys, use_store, scratch_repo):
    use_store(_seed_memory_graph(scratch_repo))
    code = main([
        "repair", "--graph", "memory://t", "--repo", str(scratch_repo), "--no-colour",
    ])
    out = capsys.readouterr().out
    assert code == 0
    assert "row_lock" in out
    source = (scratch_repo / "checkout_service" / "webhooks.py").read_text("utf-8")
    assert "db.session(for_update=True)" not in source, "a dry run must not edit"


def test_repair_command_apply_writes(capsys, use_store, scratch_repo):
    import shutil

    use_store(_seed_memory_graph(scratch_repo))
    try:
        code = main([
            "repair", "--graph", "memory://t", "--repo", str(scratch_repo),
            "--apply", "--no-colour",
        ])
        out = capsys.readouterr().out
        assert code == 0
        patched = (scratch_repo / "checkout_service" / "webhooks.py").read_text("utf-8")
        assert "db.session(for_update=True)" in patched
        assert "repaired 2 file(s)" in out
    finally:
        for backup in scratch_repo.rglob("*.orig"):
            shutil.copy(backup, str(backup)[: -len(".orig")])


